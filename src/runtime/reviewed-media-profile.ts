export function getReviewedMediaProfile(environment: Readonly<Record<string, string | undefined>>): ReviewedMediaProfile {
  const value = environment[REVIEWED_MEDIA_PROFILE_ENV];
  if (value === undefined || value === "" || value === "default") return "default";
  if (value === "all-supported") return value;
  throw new Error(`Invalid ${REVIEWED_MEDIA_PROFILE_ENV} configuration.`);
}

export function isReviewedMediaFlagEnabled(
  flagName: string,
  explicitValue: string | undefined,
  environment: Readonly<Record<string, string | undefined>>
): boolean {
  if (explicitValue !== undefined) {
    if (explicitValue === "" || explicitValue === "0") return false;
    if (explicitValue === "1") return true;
    throw new Error(`Invalid ${flagName} configuration.`);
  }
  return getReviewedMediaProfile(environment) === "all-supported" && CURATED_MEDIA_FLAGS.has(flagName);
}

export function resolveReviewedMediaBinaryPath(
  explicitValue: string | undefined,
  sharedValue: string | undefined
): string | undefined {
  return explicitValue ?? sharedValue ?? undefined;
}
