const MP4_BYTES = Buffer.from(MP4_FIXTURE_BASE64, "base64");
const FORMAT_NAME = "mov,mp4,m4a,3gp,3g2,mj2";

interface Timing { readonly start_time?: string; readonly duration?: string; }

async function makeFfprobe(output: string): Promise<{ readonly directory: string; readonly path: string }> {
  const directory = await mkdtemp(join(tmpdir(), "syntx-k4-duration-2142-"));
  const interpreter = join(directory, "node");
  const path = join(directory, "ffprobe-fixture");
  await symlink(process.execPath, interpreter);
  const script = "#!/" + interpreter + "\nprocess.stdout.write(" + JSON.stringify(output) + ");\n";
  await writeFile(path, script, { encoding: "utf8", mode: 0o700, flag: "wx" });
  await chmod(path, 0o700);
  return { directory, path };
}

function probeOutput(videoTiming: Timing, audioTiming: Timing, formatDuration = "5.000000"): string {
  return JSON.stringify({
    streams: [
      { codec_type: "video", codec_name: "h264", width: 700, height: 700, ...videoTiming },
      { codec_type: "audio", codec_name: "aac", ...audioTiming }
    ],
    format: { format_name: FORMAT_NAME, duration: formatDuration }
  });
}

function input(ffprobePath: string): Record<string, unknown> {
  return { filename: "source.mp4", mime_type: "video/mp4", bytes: MP4_BYTES, ffprobePath };
}

test("separates video file duration from max fresh audio/video track end for cost", async () => {
  const fake = await makeFfprobe(probeOutput(
    { start_time: "0.000000", duration: "4.000000" },
    { start_time: "0.500000", duration: "5.000000" },
    "5.000000"
  ));
  try {
    const result = await validateOwnerKling4OmniVideo(input(fake.path));
    assert.equal(result.metadata.duration_seconds, 5);
    assert.equal(Reflect.get(result.metadata, "input_cost_duration_seconds"), 5.5);
    releaseValidatedOwnerKling4OmniVideo(result);
  } finally { await rm(fake.directory, { recursive: true, force: true }); }
});

test("rejects missing or non-finite timing for any relevant audio/video track", async () => {
  const cases = [
    probeOutput({ start_time: "0.000000", duration: "4.000000" }, { duration: "5.000000" }),
    probeOutput({ duration: "4.000000" }, { start_time: "0.500000", duration: "5.000000" }),
    probeOutput({ start_time: "0.000000", duration: "4.000000" }, { start_time: "0.500000", duration: "N/A" })
  ];
  for (const output of cases) {
    const fake = await makeFfprobe(output);
    try {
      await assert.rejects(validateOwnerKling4OmniVideo(input(fake.path)), (error: unknown) =>
        error instanceof OwnerKling4OmniVideoPolicyError && error.code === "UNSUPPORTED_MEDIA_METADATA");
    } finally { await rm(fake.directory, { recursive: true, force: true }); }
  }
});
